function list(items: string[], fallback = "Not detected"): string {
  return items.length > 0 ? items.join(", ") : fallback;
}

function badge(label: string, message: string, color: string): string {
  const enc = (s: string) => encodeURIComponent(s.replace(/-/g, "--").replace(/_/g, "__"));
  return `![${label}](https://img.shields.io/badge/${enc(label)}-${enc(message)}-${color})`;
}

function badges(a: RepoAnalysis): string {
  const parts: string[] = [];
  if (a.license) parts.push(badge("license", a.license, "blue"));
  if (a.language) parts.push(badge("language", a.language, "informational"));
  if (a.framework) parts.push(badge("framework", a.framework, "black"));
  parts.push(badge("docs by", "SmartDocs", "6d28d9"));
  return parts.join(" ");
}

function installCommand(a: RepoAnalysis): string {
  switch (a.packageManager) {
    case "pnpm": return "pnpm install";
    case "yarn": return "yarn install";
    case "bun": return "bun install";
    case "npm": return "npm install";
    case "poetry": return "poetry install";
    case "pipenv": return "pipenv install";
    case "pip": return "pip install -r requirements.txt";
    case "cargo": return "cargo build";
    case "go modules": return "go mod download";
    default: return "npm install";
  }
}

function runCommand(a: RepoAnalysis, script: string): string {
  const pm = a.packageManager ?? "npm";
  if (!(script in a.scripts)) return "";
  if (pm === "yarn") return `yarn ${script}`;
  if (pm === "pnpm") return `pnpm ${script}`;
  if (pm === "bun") return `bun run ${script}`;
  return `npm run ${script}`;
}

