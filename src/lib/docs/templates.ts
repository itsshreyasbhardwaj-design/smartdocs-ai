const GENERATORS: Record<DocType, (a: RepoAnalysis) => string> = {
  readme,
  api,
  architecture,
  "folder-structure": folderStructure,
  installation,
  setup,
  "env-vars": envVars,
  database,
  features,
  components,
  onboarding,
  deployment,
  faq,
  contributing,
  changelog: () => changelog(),
};

export function generateTemplate(docType: DocType, analysis: RepoAnalysis): string {
  return GENERATORS[docType](analysis);
}
